function unique(values: string[]) {
  return [...new Set(values)]
}

export function getUsageGuidance(item: AnimationItem): UsageGuidance {
  const override = itemOverrides[item.id]
  if (override?.useCases && override.avoidCases) {
    return {
      useCases: override.useCases,
      avoidCases: override.avoidCases,
    }
  }

  const searchable = `${item.title} ${item.description} ${item.tags.join(' ')}`.toLowerCase()
  const matched = guidanceRules.filter((rule) =>
    rule.keywords.some((keyword) => searchable.includes(keyword.toLowerCase())),
  )

  const useCases = unique([
    ...(override?.useCases ?? []),
    ...matched.flatMap((rule) => rule.useCases),
    ...categoryGuidance[item.category].useCases,
    ...triggerGuidance[item.trigger].useCases,
  ]).slice(0, 3)

  const avoidCases = unique([
    ...(override?.avoidCases ?? []),
    ...matched.flatMap((rule) => rule.avoidCases),
    ...categoryGuidance[item.category].avoidCases,
    ...triggerGuidance[item.trigger].avoidCases,
  ]).slice(0, 2)

  return { useCases, avoidCases }
}
